from pathlib import Path
from layout import keys
from pcb.scripts.design import GPIO_NETS
ROOT=Path(__file__).resolve().parents[1]

def gpio(net):
 """RP2040 GPIO number of a net in pcb/scripts/design.py."""
 return GPIO_NETS.index(net)

def pins_dtsi():
 """Matrix and display pins from the electrical source, so the board files cannot drift from the PCB."""
 rows=sorted(n for n in GPIO_NETS if n and n.startswith('ROW'))
 cols=sorted((n for n in GPIO_NETS if n and n.startswith('COL')),key=lambda n:int(n[3:]))
 row_gpios=',\n   '.join(f'<&gpio0 {gpio(n)} (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>' for n in rows)
 col_gpios=',\n   '.join(f'<&gpio0 {gpio(n)} GPIO_ACTIVE_HIGH>' for n in cols)
 return f'''/* Generated by tools/firmware_layout.py from pcb/scripts/design.py GPIO_NETS. */
/ {{
 kscan0: kscan {{
  compatible = "zmk,kscan-gpio-matrix";
  diode-direction = "col2row";
  row-gpios = {row_gpios};
  col-gpios = {col_gpios};
 }};
}};
&pinctrl {{
 spi0_default: spi0_default {{
  group1 {{ pinmux = <SPI0_SCK_P{gpio("DISP_SCK")}>, <SPI0_TX_P{gpio("DISP_MOSI")}>; }};
 }};
}};
&spi0 {{
 status = "okay";
 pinctrl-0 = <&spi0_default>;
 pinctrl-names = "default";
 cs-gpios = <&gpio0 {gpio("DISP_CS")} GPIO_ACTIVE_HIGH>;
 nice_view: ls0xx@0 {{
  compatible = "sharp,ls0xx";
  reg = <0>;
  spi-max-frequency = <1000000>;
  width = <160>;
  height = <68>;
  serial-vcom-inversion;
  serial-vcom-interval = <33>;
 }};
}};
'''

def main():
 b=ROOT/'firmware/boards/worxbend/worxboard_ergo';ks=keys()
 transform=' '.join(f'RC({i//15},{i%15})' for i,k in enumerate(ks))
 physical=[]
 for k in ks:
  # positions/widths in 1/100 key units; rotation origin is key center.
  w=round(k.w*100);x=round(k.x/19.05*100)-w//2;y=round(k.y/19.05*100)-50
  angle=round(k.angle*100)
  def dt(n):return str(n) if n>=0 else f'({n})'
  physical.append(' <&key_physical_attrs '+ ' '.join(map(dt,[w,100,x,y,angle,x+w//2,y+50]))+'>')
 text='''/* Generated by tools/firmware_layout.py. */
#include <physical_layouts.dtsi>
#include <dt-bindings/zmk/matrix_transform.h>
/ {
 ergo_transform: keymap_transform {
  compatible = "zmk,matrix-transform";
  rows = <MATRIX_ROWS>; columns = <15>;
  map = <'''+transform+'''>;
 };
 ergo_layout: ergo_layout {
  compatible = "zmk,physical-layout";
  display-name = "Split Planck 48";
  transform = <&ergo_transform>;
  kscan = <&kscan0>;
  keys ='''+','.join(physical)+''';
 };
};
'''
 text=text.replace('MATRIX_ROWS',str(sum(1 for n in GPIO_NETS if n and n.startswith('ROW'))))
 (b/'worxboard-ergo-layout.dtsi').write_text(text)
 (b/'worxboard-ergo-pins.dtsi').write_text(pins_dtsi())
 base=[]
 for k in ks:
  if k.code=='FN': base.append('&mo 1')
  elif k.code=='RAISE': base.append('&mo 2')
  else: base.append('&kp '+k.code)
 # Lower layer carries the number row and function keys this 4-row grid does not show.
 fn_map={'Q':'N1','W':'N2','E':'N3','R':'N4','T':'N5','Y':'N6','U':'N7','I':'N8','O':'N9','P':'N0',
         'A':'F1','S':'F2','D':'F3','F':'F4','G':'F5','H':'F6','J':'F7','K':'F8','L':'F9','SEMI':'F10',
         'SQT':'F11','BSPC':'DEL','UP':'PG_UP','DOWN':'PG_DN','LEFT':'HOME','RIGHT':'END'}
 fn=['&kp '+fn_map[k.code] if k.code in fn_map else '&trans' for k in ks]
 maintenance=['&trans']*len(ks)
 maintenance[next(i for i,k in enumerate(ks) if k.code=='ESC')]='&bootloader'
 maintenance[next(i for i,k in enumerate(ks) if k.code=='TAB')]='&sys_reset'
 text='#include <behaviors.dtsi>\n#include <dt-bindings/zmk/keys.h>\n/ { keymap { compatible = "zmk,keymap";\n'
 for name,label,bindings in [('base','BASE',base),('lower','LOWER',fn),('raise','RAISE',maintenance)]:
  text+=f'{name} {{ label = "{label}"; bindings = <'+ ' '.join(bindings)+'>; };\n'
 text+='}; };\n'
 (b/'worxboard_ergo.keymap').write_text(text)
if __name__=='__main__':main()
